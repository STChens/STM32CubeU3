/**
 * @brief Middleware HSP Run Complex FFT Function
 * @param None
 * @retval 0 if success, else an error
 */
uint32_t APP_HSP_Engine_RunCFFT(void)
{
  uint32_t dominant_frequencies[NB_DOMINANT_FREQUENCY] = {0U, 0U};
  uint32_t idx_fq = 0U;
  uint32_t nb_dominant_fq = 0U;
  hsp_bram_resources_t *p_bram_rsrc = MX_HSP_BRAM_GetResources();
 
  /* ----- Transfer the samples into BRAM buffer ----- */
  memcpy(p_bram_rsrc->p_buff_cfft, input_signal_samples, HSP_BRAM_RSRC_INPUT_DATA_SIZE * sizeof(int32_t));

  /* ------Convert the Q1.31 values to Float 32 ------ */
  HSP_ACC_VectQ312F(&hmw, (int32_t *)p_bram_rsrc->p_buff_cfft, p_bram_rsrc->p_buff_cfft, HSP_BRAM_RSRC_INPUT_DATA_SIZE);

  /* ----- Execute the CFFT ----- */
  HSP_ACC_Fft_f32(&hmw, p_bram_rsrc->p_buff_cfft, HSP_LOG2NBP_256, 0U, 1U);

  /* Compute the magnitude of CFFT */
  HSP_ACC_CmplxMag_f32(&hmw, p_bram_rsrc->p_buff_cfft, p_bram_rsrc->p_cfft_magnitude, HSP_BRAM_RSRC_CFFT_RESULT_SIZE);

  /* ----- Check the results -----*/
  /* Calculate the difference between the reference output signal and the RFFT result (complex part) */
  for (uint32_t idx = 0; idx < HSP_BRAM_RSRC_CFFT_RESULT_SIZE; idx++)
  {
    float b = p_bram_rsrc->p_cfft_magnitude[idx];
    if (b > 50)
    {
      /* Retrieve the dominant Frequency related to the CFFT index */
      /* f(k) = k * fs / N                                        */
      dominant_frequencies[idx_fq] = idx * SAMPLING_FREQUENCY / HSP_BRAM_RSRC_CFFT_RESULT_SIZE;
      idx_fq++;
    }
  }

  nb_dominant_fq = idx_fq;

  /* Check Expected Dominant Frequencies */
  if (nb_dominant_fq != 2U)
  {
    return 1;
  }

  if ((dominant_frequencies[0] != 13U) || (dominant_frequencies[1] != 34U))
  {
    return 1;
  }

  return 0;
}
