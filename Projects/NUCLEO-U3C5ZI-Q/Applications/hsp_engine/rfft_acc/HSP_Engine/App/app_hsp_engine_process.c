/**
 * @brief Middleware HSP Run RFFT Function
 * @param None
 * @retval 0 if success, else an error
 */
uint32_t APP_HSP_Engine_RunRFFT(void)
{
  uint32_t dominant_frequencies[NB_DOMINANT_FREQUENCY] = {0U, 0U};
  uint32_t idx_fq = 0U;
  uint32_t nb_dominant_fq = 0U;
  hsp_bram_resources_t *p_bram_rsrc = MX_HSP_BRAM_GetResources();

  /* ----- Transfer the samples into BRAM buffer ----- */
  memcpy(p_bram_rsrc->p_buff_rfft, input_signal_samples, HSP_BRAM_RSRC_INPUT_SAMPLES_SIZE * sizeof(float32_t));

  /* ----- Execute the RFFT ----- */
  HSP_ACC_Rfft_f32(&hmw, p_bram_rsrc->p_buff_rfft, HSP_LOG2NBP_512, 0U, 1U, HSP_RFFT_TYPE_1);

  /* Compute the magnitude of RFFT results */
  HSP_ACC_VectAbs_f32(&hmw, p_bram_rsrc->p_buff_rfft, p_bram_rsrc->p_rfft_magnitude, HSP_BRAM_RSRC_RFFT_RESULT_SIZE);

  /* ----- Check the results -----*/
  /* Calculate the difference between the reference output signal and the RFFT result (complex part) */
  for (uint32_t idx = 0; idx < HSP_BRAM_RSRC_RFFT_RESULT_SIZE; idx++)
  {
    float b = p_bram_rsrc->p_rfft_magnitude[idx];
    if (b > 10)
    {
      /* Retrieve the RFFT Frequency related to the index */
      /* Because of HSP RFFT returned a buffer of complex value, idx shall be divide by 2 */
      /* f(k) = k * fs / N                              */
      dominant_frequencies[idx_fq] = (idx / 2) * SAMPLING_FREQUENCY / HSP_BRAM_RSRC_INPUT_SAMPLES_SIZE;
      idx_fq++;
    }
  }

  nb_dominant_fq = idx_fq;

  /* Check Expected Dominant Frequencies */
  if (nb_dominant_fq != 2U)
  {
    return 1;
  }

  if ((dominant_frequencies[0] != 50U) || (dominant_frequencies[1] != 200U))
  {
    return 1;
  }

  return 0;
}
