/**
  * @brief Middleware HSP Run Biquad Cascade DF1 Function
  * @param None
  * @retval 0 if success, else an error
  */
uint32_t APP_HSP_Engine_RunBiquadCascadeDF1(void)
{
  hsp_bram_resources_t *p_bram_rsrc = MX_HSP_BRAM_GetResources();

  /* ----- Transfer the Samples & Coef into BRAM buffers ----- */
  /* Load Input Samples into "p_buff_in" buffer allocated in HSP BRAM */
  memcpy(p_bram_rsrc->p_buff_in, input_signal_samples, HSP_BRAM_RSRC_INPUT_SIGNAL_SAMPLES_SIZE * sizeof(float32_t));

  /* Load Coeff into "p_coef" buffer allocated in HSP BRAM */
  memcpy(p_bram_rsrc->p_coef, biquad_coefs, HSP_BRAM_RSRC_BIQUAD_COEF_SIZE * sizeof(float32_t));

  HSP_ACC_BiquadCascadeDf1_f32(&hmw, p_bram_rsrc->p_buff_in, p_bram_rsrc->p_coef, p_bram_rsrc->biquad_state_id, p_bram_rsrc->p_buff_out, HSP_BRAM_RSRC_INPUT_SIGNAL_SAMPLES_SIZE);

  /* ----- Clear the State Buffer for reuse ----- */
  HSP_ACC_BiquadCascadeDf1ResetStateBuffer(&hmw, p_bram_rsrc->biquad_state_id);

  /* ----- Check the results -----*/
  /* Calculate the difference between the reference output signal and the filtered output signal */
  for (uint32_t idx = 0; idx < HSP_BRAM_RSRC_OUTPUT_SAMPLES_SIZE; idx++)
  {
    fir_results_error[idx] = p_bram_rsrc->p_buff_out[idx] - biquad_results_ref[idx];
  }

  /* Calculate the RMS (Root Mean Square) value */
  float rms_kpi = 0.0f;
  arm_rms_f32(fir_results_error, HSP_BRAM_RSRC_OUTPUT_SAMPLES_SIZE, &rms_kpi);
  if (rms_kpi > RMS_REF)
  {
    return 1;
  }

  return 0;
}
